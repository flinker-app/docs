const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const docsRoot = path.resolve(__dirname, "..");
const source = path.resolve(process.argv[2] || "../ifc-viewer-examples");
const mediaDirectory = "_media/ifc-viewer-examples";
const marker = "<!-- Generated by scripts/sync-viewer-examples.js. -->";
const catalog = JSON.parse(fs.readFileSync(path.join(source, "catalog/catalog.json"), "utf8"));
const { url: sdkUrl } = JSON.parse(fs.readFileSync(path.join(source, "viewer-sdk.config.json"), "utf8"));
const version = new URL(sdkUrl).pathname.split("/")[2];
const examples = catalog.examples;
const files = new Map();
const quote = JSON.stringify;
const escapeHtml = value => value.replace(/[&<>"']/g, character =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]);

assert.ok(Array.isArray(examples) && examples.length, "The examples catalog is empty");
assert.match(sdkUrl, /^https:\/\/cdn\.flinker\.app\/ifc-viewer\/v\d+\.\d+\.\d+\/ifc-viewer\.es\.js(?:\?[^\s]*)?$/, "Expected the pinned SDK URL used by the examples");

// Read every source before writing anything, so an incomplete checkout cannot erase the docs.
for (const example of examples) {
  const { id, title, description, guideHtml, noticesHtml } = example;
  assert.match(id, /^[a-zA-Z0-9][a-zA-Z0-9_-]*$/);
  assert.ok(title && description && guideHtml && noticesHtml, `${id}: incomplete catalog entry`);
  const html = fs.readFileSync(path.join(source, "examples", id, "index.html"));
  assert.ok(html.toString().includes(sdkUrl), `${id}: SDK URL does not match viewer-sdk.config.json`);
  files.set(`${mediaDirectory}/${id}/index.html`, html);
  files.set(`${mediaDirectory}/${id}/thumbnail.webp`, fs.readFileSync(path.join(source, "examples", id, "thumbnail.webp")));
  const url = `/${mediaDirectory}/${id}/index.html`;
  const tabId = id.toLowerCase().replace(/_/g, "-");
  const guide = guideHtml.replace(/<h2\b[^>]*data-example-title[^>]*>[\s\S]*?<\/h2>\s*/i, "")
    .replace(/<p\b[^>]*data-example-description[^>]*>[\s\S]*?<\/p>\s*/i, "");
  files.set(`docs/ifc-viewer-sdk-example-${id}.md`, `---
title: ${quote(title)}
description: ${quote(description)}
exampleUrl: ${quote(url)}
---
# ${title}

${marker}

${description}

# [Preview](#tab/${tabId}-preview)

<iframe title="${escapeHtml(title)}" src="${url}" width="100%" height="720" loading="lazy" allow="fullscreen" allowfullscreen style="border:0;max-width:100%;"></iframe>

# [Code](#tab/${tabId}-code)

[!code-html[](..${url})]

---

## How it works

${guide}

${noticesHtml}
`);
}

const ids = new Set(examples.map(example => example.id));
const aliases = { ifc: "west-riverside-hospital", "bcf-topics": "bcf", "bcf-selection": "selection", ids: "s1-ids" };
const redirect = target => {
  const article = ids.has(target) ? `ifc-viewer-sdk-example-${target}` : "ifc-viewer-sdk-examples";
  const url = `https://docs.flinker.app/docs/${article}.html`;
  return `---\ntitle: IFC Viewer examples\nredirect_url: ${url}\ncanonical_url: ${url}\n---\n# IFC Viewer examples\n\n${marker}\n\n[Open the updated examples](${article}.${ids.has(target) ? "md" : "yml"}).\n`;
};
for (const [alias, target] of Object.entries(aliases)) files.set(`docs/ifc-viewer-sdk-example-${alias}.md`, redirect(target));

// Preserve links to the old individual embeds and to examples removed from the catalog.
const legacyEmbeds = { ...aliases, "load-existing-bcf": "bcf", "create-bcf-topic": "view-link",
  "bcf-coloring": "bcf-coloring", "bcf-clipping": "bcf-clipping", "bcf-clipping-section": "bcf-clipping",
  "bcf-clipping-section-box": "bcf-clipping", "bcf-visibility-hide-doors-windows": "bcf-visibility",
  "bcf-visibility-show-doors-windows": "bcf-visibility", "bcf-visibility-hide-spaces-boundaries-openings": "bcf-visibility",
  "bcf-visibility-show-spaces-only": "bcf-visibility" };
for (const [alias, target] of Object.entries(legacyEmbeds)) {
  const url = ids.has(target) ? `/${mediaDirectory}/${target}/index.html` : "/docs/ifc-viewer-sdk-examples.html";
  files.set(`_media/ifc-viewer-sdk-example-${alias}.html`, `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>IFC Viewer example</title><meta http-equiv="refresh" content="0;url=${url}"></head><body><a href="${url}">Open the updated example</a></body></html>\n`);
}
for (const filename of fs.readdirSync(path.join(docsRoot, "docs"))) {
  const name = `docs/${filename}`;
  if (filename.startsWith("ifc-viewer-sdk-example-") && !files.has(name)) files.set(name, redirect(null));
}

files.set("docs/ifc-viewer-sdk-examples.yml", `### YamlMime:Dashboard
---
title: IFC Viewer SDK examples
description: Explore standalone IFC, BCF, IDS, point cloud, map and host integration examples.
documentType: dashboard
_disableAffix: true
_disableBreadcrumb: true
_disableNextArticle: true
expanded: true
# Generated by scripts/sync-viewer-examples.js.
items:
` + examples.map(example => `  - name: ${quote(example.title)}\n    thumbnail: /${mediaDirectory}/${example.id}/thumbnail.webp\n    description: ${quote(example.description)}\n    href: ifc-viewer-sdk-example-${example.id}.html\n`).join(""));

const toc = fs.readFileSync(path.join(docsRoot, "docs/toc.yml"), "utf8");
const navigation = /      # generated:viewer-examples:start[\s\S]*?      # generated:viewer-examples:end/;
assert.match(toc, navigation, "Missing example navigation markers");
files.set("docs/toc.yml", toc.replace(navigation, "      # generated:viewer-examples:start\n" + examples.map(example =>
  `        - name: ${quote(example.title)}\n          href: ifc-viewer-sdk-example-${example.id}.md`).join("\n") + "\n      # generated:viewer-examples:end"));

const guide = fs.readFileSync(path.join(docsRoot, "docs/ifc-viewer-sdk.md"), "utf8");
files.set("docs/ifc-viewer-sdk.md", guide.replace(/https:\/\/cdn\.flinker\.app\/ifc-viewer\/v\d+\.\d+\.\d+\/ifc-viewer\.es\.js(?:\?[^\s"'`<>]+)?/g, sdkUrl)
  .replace(/IFC Viewer SDK `v\d+\.\d+\.\d+`/g, `IFC Viewer SDK \`${version}\``));

for (const [name, content] of files) {
  const filename = path.join(docsRoot, name);
  const bytes = Buffer.from(content);
  if (fs.existsSync(filename) && fs.readFileSync(filename).equals(bytes)) continue;
  fs.mkdirSync(path.dirname(filename), { recursive: true });
  fs.writeFileSync(filename, bytes);
}
console.log(`Updated ${examples.length} embedded examples and their documentation from ${source}.`);
